//! The 64 bytes that the S-SMP shows at 0xFFC0 to 0xFFFF while bit 7 of the
//! control register is set. They are a program written for this core from the
//! documented behavior: clear the zero page, announce 0xAA and 0xBB on ports 0
//! and 1, wait for 0xCC, then take blocks from the main CPU through the ports
//! until a block with command 0 gives the entry address. Games jump to 0xFFC0
//! to start over and to 0xFFC9 to announce again, and both addresses start an
//! instruction here.
//!
//! One block takes at most 256 bytes.

pub const BASE: u16 = 0xFFC0;

pub const ROM: [u8; 64] = [
    // FFC0: clear 0x01..0xEF
    0xCD, 0xEF, 0xBD, 0xE8, 0x00, 0xC6, 0x1D, 0xD0, 0xFC,
    // FFC9: announce, then wait for 0xCC on port 0
    0x8F, 0xAA, 0xF4, 0x8F, 0xBB, 0xF5, 0x78, 0xCC, 0xF4, 0xD0, 0xFB,
    // FFD4: take the address, the command and the kick; answer the kick
    0xBA, 0xF6, 0xDA, 0x00, 0xBA, 0xF4, 0xC4, 0xF4, 0x5D, 0xDD, 0xD0, 0x04,
    // FFE0: command 0 enters the program
    0x5D, 0x1F, 0x00, 0x00,
    // FFE4: take bytes while port 0 counts up
    0x8D, 0x00, 0x7E, 0xF4, 0xF0, 0x06, 0x3E, 0xF4, 0xF0, 0xF8, 0x2F, 0xE4,
    0xE4, 0xF5, 0xCB, 0xF4, 0xD7, 0x00, 0xDD, 0x5D, 0xFC, 0xD0, 0xEB, 0x2F,
    0xD7, 0x00,
    // FFFE: reset vector
    0xC0, 0xFF,
];
